"""Generate THIRD_PARTY_NOTICES.md from the dependency manifests and installed metadata.

Run from the repository root:  python scripts/notices.py
The output is deterministic: same packages and versions produce the same file.
Npm entries read node_modules/<name>/package.json; Python entries use importlib.metadata.
Missing metadata prints "see project page" rather than guessing a licence.
"""
from __future__ import annotations

import json
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD_PARTY_NOTICES.md"


def npm_rows():
    package = json.loads((ROOT / "frontend" / "package.json").read_text(encoding="utf-8"))
    names = sorted({**package.get("dependencies", {}), **package.get("devDependencies", {})})
    rows = []
    for name in names:
        info = ROOT / "frontend" / "node_modules" / name / "package.json"
        version, licence = "see project page", "see project page"
        if info.is_file():
            data = json.loads(info.read_text(encoding="utf-8"))
            version = data.get("version") or version
            value = data.get("license")
            if isinstance(value, dict):
                value = value.get("type")
            licence = value or licence
        rows.append((name, version, licence, f"https://www.npmjs.com/package/{name}"))
    return rows


def python_rows():
    files = ("requirements.txt", "requirements-stt.txt")
    names = set()
    for rel in files:
        path = ROOT / "backend" / rel
        if not path.is_file():
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if not line or line.startswith("-"):
                continue
            name = line.split("==")[0].split(">=")[0].split("[")[0].strip()
            if name:
                names.add(name)
    rows = []
    for name in sorted(names):
        try:
            version = metadata.version(name)
            info = metadata.metadata(name)
            licence = info.get("License-Expression") or info.get("License") or "see project page"
            if len(licence) > 60:
                licence = "see project page"
        except metadata.PackageNotFoundError:
            version, licence = "not installed here", "see project page"
        rows.append((name, version, licence, f"https://pypi.org/project/{name}/"))
    return rows


def table(rows):
    lines = ["| Package | Version | Licence | Link |", "|---|---|---|---|"]
    lines += [f"| `{name}` | {version} | {licence} | [project page]({url}) |" for name, version, licence, url in rows]
    return "\n".join(lines)


def main():
    text = "\n".join([
        "# Third-party notices",
        "",
        "This file is generated by `scripts/notices.py` from `frontend/package.json`, the backend",
        "requirements files and the installed package metadata. Re-run it after changing a dependency.",
        "Each project keeps its own licence; the entries below are a thank-you, not a licence change.",
        "",
        "## Frontend packages",
        "",
        table(npm_rows()),
        "",
        "## Backend packages",
        "",
        table(python_rows()),
        "",
        "Direct services called by the app (Google Gemini API, Groq, optional Ollama, optional",
        "Supabase) are governed by their own terms. The browser Web Speech API is provided by the",
        "user's browser; no audio leaves the page.",
        "",
    ])
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
